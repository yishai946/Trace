"""Writes a Markdown copy of the MVP specification into docs/Specifications/md/, for agents to read cheaply.

The .docx and .xlsx files stay the source of truth. Run again after any of them changes:
    python docs/Specifications/to_markdown.py
Uses only the standard library.
"""

import re
import zipfile
from html import unescape
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "md"
UC_SPEC = HERE / "01_TRACE_MVP_Use_Case_Specification_HE.docx"
RULES = HERE / "02_TRACE_MVP_State_and_Rules_Reference_HE.docx"
DECISIONS = HERE / "04_TRACE_MVP_Decision_Log_QA_HE.xlsx"
GENERATED = "<!-- Generated by docs/Specifications/to_markdown.py from {source}. Do not edit; edit the source and run it again. -->\n\n"


def text_of(xml: str) -> str:
    """The visible text of a run of WordprocessingML, with tabs and line breaks kept as spaces."""
    xml = re.sub(r"<w:(tab|br)\b[^>]*/>", " ", xml)
    return unescape(re.sub(r"<[^>]+>", "", xml)).strip()


def cell_text(xml: str) -> str:
    paragraphs = [text_of(p) for p in re.findall(r"<w:p[ >].*?</w:p>", xml, re.S)]
    return " ".join(p for p in paragraphs if p).replace("|", "\\|")


def md_table(rows: list[list[str]]) -> str:
    rows = [r for r in rows if any(c.strip() for c in r)]
    if not rows:
        return ""
    width = max(len(r) for r in rows)
    rows = [r + [""] * (width - len(r)) for r in rows]
    lines = ["| " + " | ".join(rows[0]) + " |", "|" + "---|" * width]
    lines += ["| " + " | ".join(r) + " |" for r in rows[1:]]
    return "\n".join(lines)


def docx_blocks(path: Path) -> list[tuple[str, str]]:
    """The document body in order, as (kind, markdown) pairs; kind is the heading level ('h1'..'h3') or 'text'."""
    xml = zipfile.ZipFile(path).read("word/document.xml").decode("utf-8")
    blocks = []
    for block in re.findall(r"<w:tbl>.*?</w:tbl>|<w:p[ >].*?</w:p>", xml, re.S):
        if block.startswith("<w:tbl>"):
            rows = [
                [cell_text(c) for c in re.findall(r"<w:tc>.*?</w:tc>", row, re.S)]
                for row in re.findall(r"<w:tr[ >].*?</w:tr>", block, re.S)
            ]
            table = md_table(rows)
            if table:
                blocks.append(("text", table))
            continue
        text = text_of(block)
        if not text:
            continue
        style = re.search(r'<w:pStyle w:val="([^"]+)"', block)
        style = style.group(1) if style else ""
        heading = re.fullmatch(r"Heading([1-3])", style)
        if heading:
            blocks.append((f"h{heading.group(1)}", text))
        elif style.startswith("List"):
            blocks.append(("text", f"- {text}"))
        else:
            blocks.append(("text", text))
    return blocks


def render(blocks: list[tuple[str, str]], shift: int = 0) -> str:
    """Markdown for blocks; `shift` raises headings (shift 1 turns h2 into #)."""
    out = []
    for kind, text in blocks:
        if kind == "text":
            out.append(text)
        else:
            level = max(1, int(kind[1]) - shift)
            out.append("#" * level + " " + text)
    # Consecutive list items stay together; everything else is separated by a blank line.
    md = ""
    for i, part in enumerate(out):
        joiner = "\n" if i and part.startswith("- ") and out[i - 1].startswith("- ") else "\n\n"
        md += (joiner if i else "") + part
    return md + "\n"


def write(name: str, source: Path, body: str) -> None:
    path = OUT / name
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(GENERATED.format(source=source.name) + body, encoding="utf-8", newline="\n")


def use_case_spec() -> list[tuple[str, str]]:
    """Splits the use case spec into an overview and one file per use case. Returns (id, title) per use case."""
    blocks = docx_blocks(UC_SPEC)
    overview, cases, current = [], [], None
    in_state_models = False
    for kind, text in blocks:
        if kind == "h1":
            in_state_models = text.startswith("5.")
        elif in_state_models and kind == "text":
            # Section 5 writes each state flow for right-to-left reading ("A ← B" means A, then B); every other
            # source writes the same flows as "A → B". Turn them around so the copy reads the same as the rest.
            text = text.replace("←", "→")
        uc = re.match(r"(UC-[CFS]\d+)\s*[—-]\s*(.+)", text) if kind == "h2" else None
        if uc:
            current = (uc.group(1), uc.group(2), [])
            cases.append(current)
        elif kind == "h1":
            current = None
            overview.append((kind, text))
        elif current:
            current[2].append((kind, text))
        else:
            overview.append((kind, text))
    write("overview.md", UC_SPEC, "# אפיון ה-MVP: סקירה\n\n" + render(overview, shift=-1))
    for uc_id, title, body in cases:
        write(f"use-cases/{uc_id}.md", UC_SPEC, f"# {uc_id}: {title}\n\n" + render(body, shift=1))
    return [(uc_id, title) for uc_id, title, _ in cases]


def xlsx_sheets(path: Path) -> list[tuple[str, list[list[str]]]]:
    z = zipfile.ZipFile(path)
    strings = [
        unescape(re.sub(r"<[^>]+>", "", s))
        for s in re.findall(r"<(?:x:)?si>.*?</(?:x:)?si>", z.read("xl/sharedStrings.xml").decode("utf-8"), re.S)
    ]
    workbook = z.read("xl/workbook.xml").decode("utf-8")
    rels = z.read("xl/_rels/workbook.xml.rels").decode("utf-8")
    targets = dict(re.findall(r'Target="/?([^"]+)"[^>]*Id="([^"]+)"', rels))
    targets = {rid: target for target, rid in targets.items()}
    sheets = []
    for name, rid in re.findall(r'<(?:x:)?sheet name="([^"]+)"[^>]*r:id="([^"]+)"', workbook):
        target = targets[rid]
        target = target if target.startswith("xl/") else "xl/" + target
        xml = z.read(target).decode("utf-8")
        rows = []
        for row in re.findall(r"<(?:x:)?row\b.*?</(?:x:)?row>", xml, re.S):
            cells = []
            for cell in re.findall(r"<(?:x:)?c\b[^>]*?(?:/>|>.*?</(?:x:)?c>)", row, re.S):
                value = re.search(r"<(?:x:)?v>(.*?)</(?:x:)?v>", cell, re.S)
                inline = re.search(r"<(?:x:)?is>(.*?)</(?:x:)?is>", cell, re.S)
                if 't="s"' in cell and value:
                    text = strings[int(value.group(1))]
                elif inline:
                    text = unescape(re.sub(r"<[^>]+>", "", inline.group(1)))
                else:
                    text = unescape(value.group(1)) if value else ""
                cells.append(" ".join(text.split()).replace("|", "\\|"))
            rows.append(cells)
        sheets.append((name, rows))
    return sheets


def decision_log() -> None:
    parts = ["# יומן החלטות ושאלות\n"]
    for name, rows in xlsx_sheets(DECISIONS):
        table = md_table(rows)
        if table:
            parts.append(f"## {name}\n\n{table}\n")
    write("decision-log.md", DECISIONS, "\n".join(parts))


def main() -> None:
    cases = use_case_spec()
    write("state-and-rules.md", RULES, "# מצבים וכללים\n\n" + render(docx_blocks(RULES), shift=-1))
    decision_log()
    index = [
        "# האפיון כ-Markdown\n",
        "עותק לקריאה של המסמכים ב-`docs/Specifications/`. המקור (docx/xlsx) הוא הקובע. "
        "אחרי שינוי במקור מריצים `python docs/Specifications/to_markdown.py`.\n",
        "- [overview.md](overview.md): מטרה, היקף, שחקנים, מושגים, מודלי מצבים, כללים, הרשאות ואינדקס מקרי השימוש",
        "- [state-and-rules.md](state-and-rules.md): מחזורי חיים, תנאי סף, Coverage, Offline, דוחות, הודעות ו-SOS",
        "- [decision-log.md](decision-log.md): יומן ההחלטות והשאלות (החלטה N היא השורה עם המספר N)",
        "",
        "## מקרי שימוש\n",
    ]
    index += [f"- [{uc_id}](use-cases/{uc_id}.md): {title}" for uc_id, title in cases]
    write("README.md", UC_SPEC, "\n".join(index) + "\n")
    print(f"Wrote {len(cases)} use cases, overview, state-and-rules, decision-log and README to {OUT}")


if __name__ == "__main__":
    main()
